export function t(text, vars = {}) {
  // French puts a (non-breaking) space before ? ! : ; so they never wrap alone.
  const s = fr ? text.replace(/ ([?!:;»])/g, '\u00a0$1').replace(/« /g, '«\u00a0') : (EN[text] || text)
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}
export const plural = (n, one, many) => (n === 1 ? t(one) : t(many, { n }))
export const lang = fr ? 'fr' : 'en'
